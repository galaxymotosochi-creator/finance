/**
 * Генерация уникального ID для записей.
 *
 * Раньше повсеместно использовался Date.now() — миллисекунды.
 * При быстрой вставке нескольких записей подряд (импорт пачкой,
 * офлайн-очередь) Date.now() выдавал ОДИНАКОВОЕ число → дубли ID
 * в базе → ломался key={p.id} в React-таблицах.
 *
 * Теперь: Date.now() * 1000 + счётчик 0..999.
 * Гарантирует уникальность даже в пределах одной миллисекунды.
 */
let _seq = 0;

export function genId() {
  _seq = (_seq + 1) % 1000;
  const base = Date.now() * 1000;
  // небольшой случайный разброс между вкладками, чтобы исключить коллизии
  const jitter = Math.floor(Math.random() * 1000);
  return base + ((_seq * 7 + jitter) % 1000);
}
